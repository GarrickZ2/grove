import { useEffect, useRef, type KeyboardEvent } from "react";
import { Check, ChevronDown } from "lucide-react";
import type { MetricType, Unit } from "../../components/Stats/statsModel";
import { Button, usePopover } from "../ui";
import { METRIC_LABEL } from "./statisticsView";

const METRICS: { value: MetricType; label: string; hint: string }[] = [
  { value: "total", label: "Total", hint: "Input + cached + output" },
  { value: "input", label: "Input", hint: "Fresh prompt tokens" },
  { value: "cached", label: "Cached", hint: "Replayed from the prompt cache" },
  { value: "output", label: "Output", hint: "Generated by the agent" },
];

const UNITS: { value: Unit; label: string; hint: string }[] = [
  { value: "token", label: "Tokens", hint: "As reported per turn" },
  { value: "cost", label: "Cost", hint: "Reported cost, else estimated from model pricing" },
];

interface MeasureMenuProps {
  metric: MetricType;
  unit: Unit;
  onMetric: (metric: MetricType) => void;
  onUnit: (unit: Unit) => void;
}

/** One pill for the page-wide measure: which tokens, counted as tokens or cost. */
export function MeasureMenu({ metric, unit, onMetric, onUnit }: MeasureMenuProps) {
  const { open, setOpen, toggle, rootRef } = usePopover<HTMLDivElement>();
  const menuRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    // Land on the checked measure so arrows start from the current choice.
    if (open) menuRef.current?.querySelector<HTMLButtonElement>('[aria-checked="true"]')?.focus();
  }, [open]);

  const onMenuKey = (event: KeyboardEvent<HTMLDivElement>) => {
    const items = [...(menuRef.current?.querySelectorAll<HTMLButtonElement>('[role="menuitemradio"]') ?? [])];
    const at = items.indexOf(document.activeElement as HTMLButtonElement);
    const move = (to: number) => {
      event.preventDefault();
      items[(to + items.length) % items.length]?.focus();
    };
    if (event.key === "ArrowDown") move(at + 1);
    else if (event.key === "ArrowUp") move(at - 1);
    else if (event.key === "Home") move(0);
    else if (event.key === "End") move(items.length - 1);
    else if (event.key === "Tab") setOpen(false);
  };

  return (
    <div className="ostat-measure" ref={rootRef}>
      <Button
        variant="secondary"
        className="ostat-measure-btn"
        aria-haspopup="menu"
        aria-expanded={open}
        onClick={toggle}
      >
        <span>{METRIC_LABEL[metric]}</span>
        <span className="ostat-measure-unit">{unit === "cost" ? "Cost" : "Tokens"}</span>
        <ChevronDown className={`ostat-measure-chev${open ? " is-open" : ""}`} />
      </Button>
      {open ? (
        <div className="oui-pop ostat-pop" role="menu" aria-label="Measure" ref={menuRef} onKeyDown={onMenuKey}>
          <div className="ostat-pop-label">Measure</div>
          {METRICS.map((item) => (
            <MenuRadio key={item.value} checked={item.value === metric} label={item.label} hint={item.hint} onPick={() => { onMetric(item.value); setOpen(false); }} />
          ))}
          <div className="ostat-pop-sep" role="separator" />
          <div className="ostat-pop-label">Count as</div>
          {UNITS.map((item) => (
            <MenuRadio key={item.value} checked={item.value === unit} label={item.label} hint={item.hint} onPick={() => { onUnit(item.value); setOpen(false); }} />
          ))}
        </div>
      ) : null}
    </div>
  );
}

function MenuRadio({ checked, label, hint, onPick }: { checked: boolean; label: string; hint: string; onPick: () => void }) {
  return (
    <button type="button" role="menuitemradio" aria-checked={checked} className={`ostat-pop-item${checked ? " is-sel" : ""}`} onClick={onPick}>
      <span className="ostat-pop-copy">
        <span>{label}</span>
        <small>{hint}</small>
      </span>
      {checked ? <Check className="ostat-pop-check" aria-hidden="true" /> : null}
    </button>
  );
}
